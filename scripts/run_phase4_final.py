"""Stage 4D final evaluation (master seed 4000), from the frozen manifest only.

    python scripts/run_phase4_final.py --check              # verify the freeze; plays nothing
    python scripts/run_phase4_final.py --run --workers 4    # play (resumable), then report
    python scripts/run_phase4_final.py --report             # report from completed matches

``--run`` refuses to play unless every check passes: manifest and file hashes,
library versions, model SHA-256, hero configurations, and the git tag
``phase4-freeze`` on a clean checkout. Each match is saved as soon as it ends
(data/processed/phase4_final/, git-ignored), so an interrupted run continues
where it stopped with identical results.

The report (results/phase4/stage4d_final_report.md and
stage4d_final_summary.json) states the pre-specified primary and secondary
endpoints first, then the same descriptive tables as the development report.
"""

from __future__ import annotations

import argparse
import json
import os
import platform
import sys
import time
from datetime import datetime, timezone
from pathlib import Path

from hybridpoker.dataset_generation import warm_preflop_cache
from hybridpoker.hand_log import _git_commit
from hybridpoker.opponent_predictor import file_sha256
from hybridpoker.phase4_final import (
    FINAL_DIR,
    MANIFEST_PATH,
    collect,
    jobs_from_manifest,
    load_manifest,
    primary_analysis,
    primary_lines,
    run_jobs,
    verify_for_run,
)
from hybridpoker.phase4_report import analyse

OUT = Path("results/phase4")
RUN_LOG = FINAL_DIR / "run_log.json"


def _init_worker() -> None:
    warm_preflop_cache([500, 200])


def check(manifest: dict) -> bool:
    results = verify_for_run(manifest)
    for name, problems in results.items():
        print(f"{'OK  ' if not problems else 'FAIL'} {name}")
        for problem in problems:
            print(f"       - {problem}")
    return not any(results.values())


def report(manifest: dict) -> None:
    main_jobs, replay_jobs = jobs_from_manifest(manifest)
    records = collect(main_jobs, replay_jobs, FINAL_DIR)
    log = json.loads(RUN_LOG.read_text(encoding="utf-8")) if RUN_LOG.exists() else {"sessions": []}
    sessions = log["sessions"]
    endpoints = primary_analysis(records["results"], manifest)
    data = {"deals": manifest["deals_per_match"], "heroes": manifest["heroes"], "opponents": manifest["opponents"],
            "results": records["results"], "replays": records["replays"],
            "wall_seconds": sum(s["wall_seconds"] for s in sessions), "workers": sessions[-1]["workers"] if sessions else 0,
            "git_commit_at_start": sessions[0]["git_commit"] if sessions else _git_commit(),
            "working_tree_dirty_at_start": False, "model_sha256": file_sha256(Path(manifest["model"]["path"])),
            "python": platform.python_version()}
    header = [
        "# Stage 4D final evaluation (master seed 4000)",
        "",
        "Generated by `scripts/run_phase4_final.py` from the frozen manifest "
        f"`{MANIFEST_PATH.as_posix()}` (manifest_sha256 `{manifest['manifest_sha256']}`), following "
        "`docs/phase4_analysis_plan.md`. Nothing was tuned on these results.",
        "",
        f"- Deals per match: {data['deals']} (each played twice with seats swapped).",
        f"- Opponents: {len(manifest['opponents'])} configurations (12 training-pool, 4 held-out).",
        "- Heroes: " + ", ".join(manifest["hero_labels"][h] for h in manifest["heroes"]) + ". All heroes face "
        "identical deals (`derive_seed(4000, \"eval\", opponent, 0)`); each starts with no memory.",
        f"- Code commit (tag `{manifest['freeze_tag']}`): `{data['git_commit_at_start']}`. Model SHA-256: "
        f"`{data['model_sha256']}`.",
        f"- Runtime: {data['wall_seconds'] / 3600:.2f} h over {len(sessions)} session(s); Python {data['python']}.",
        "- Uncertainty: 95% normal intervals with the deal pair as the unit. Group rows weight every opponent "
        "equally.",
        "",
        *primary_lines(endpoints),
    ]
    summary, lines = analyse(data, header=header, sample_size_section=False)
    summary["endpoints"] = endpoints
    summary.update({"manifest_sha256": manifest["manifest_sha256"], "sessions": sessions})
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "stage4d_final_report.md").write_text("\n".join(lines), encoding="utf-8", newline="\n")
    (OUT / "stage4d_final_summary.json").write_text(json.dumps(summary, indent=2, default=float) + "\n",
                                                    encoding="utf-8", newline="\n")
    print(f"wrote {OUT / 'stage4d_final_report.md'}")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--run", action="store_true")
    mode.add_argument("--report", action="store_true")
    parser.add_argument("--workers", type=int, default=4)
    args = parser.parse_args()
    manifest = load_manifest(MANIFEST_PATH)

    if args.check:
        return 0 if check(manifest) else 1
    if args.report:
        report(manifest)
        return 0

    if not check(manifest):
        print("Refusing to play: the freeze checks failed.", file=sys.stderr)
        return 1
    main_jobs, replay_jobs = jobs_from_manifest(manifest)
    started = datetime.now(timezone.utc).isoformat(timespec="seconds")
    start = time.perf_counter()
    played = run_jobs(main_jobs, replay_jobs, FINAL_DIR, run_id=started, workers=args.workers,
                      initializer=_init_worker, log=lambda m: print(m, flush=True))
    log = json.loads(RUN_LOG.read_text(encoding="utf-8")) if RUN_LOG.exists() else {"sessions": []}
    log["sessions"].append({"started": started, "wall_seconds": time.perf_counter() - start, "matches": played,
                            "workers": args.workers, "git_commit": _git_commit(),
                            "machine": {"platform": platform.platform(), "cpu_count": os.cpu_count()}})
    FINAL_DIR.mkdir(parents=True, exist_ok=True)
    RUN_LOG.write_text(json.dumps(log, indent=2) + "\n", encoding="utf-8")
    report(manifest)
    return 0


if __name__ == "__main__":
    sys.exit(main())
