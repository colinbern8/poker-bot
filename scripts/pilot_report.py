"""Data-quality, feature, leakage and runtime report for the Phase 3 pilot.

    python scripts/pilot_report.py --regenerate

Reads the pilot logs (data/raw/simulations/phase3_pilot_s3000/), builds
Feature Sets A and B, runs leakage audits L1-L11 and writes
results/phase3/pilot_report.md and pilot_report.json. With --regenerate,
match 0 is played again into a temporary folder and compared byte for
byte (audit L11b).

Labels are used here only for reporting and auditing, never as features.
"""

from __future__ import annotations

import argparse
import json
import math
import tempfile
import time
from pathlib import Path

import pandas as pd

from hybridpoker import leakage as L
from hybridpoker.action_probabilities import CLASS_ORDER
from hybridpoker.dataset_generation import generate_match
from hybridpoker.dataset_loader import load_dataset, prior_rows
from hybridpoker.dataset_manifest import (
    DEFAULT_MANIFEST_DIR,
    MAIN_MANIFEST_NAME,
    PILOT_MANIFEST_NAME,
    load_manifest,
    match_specs,
    run_dir_name,
)
from hybridpoker.features import A_FEATURES, feature_set_a
from hybridpoker.opponent_history import B_FEATURES, feature_set_b, fit_priors, player_role, prior_hand_count

DEFAULT_RAW = Path("data/raw/simulations/phase3_pilot_s3000")
DEFAULT_OUT = Path("results/phase3")
FULL_MATCHES = 48
RARE_SHARE = 0.01


def md_table(frame: pd.DataFrame, floatfmt: str = "{:.3f}") -> str:
    def cell(value) -> str:
        if isinstance(value, float):
            return floatfmt.format(value)
        return str(value)

    header = "| " + " | ".join(str(c) for c in frame.columns) + " |"
    rule = "|" + "|".join("---" for _ in frame.columns) + "|"
    rows = ["| " + " | ".join(cell(v) for v in row) + " |" for row in frame.itertuples(index=False)]
    return "\n".join([header, rule, *rows])


def action_table(frame: pd.DataFrame, by: str | None) -> pd.DataFrame:
    groups = [("all", frame)] if by is None else list(frame.groupby(by))
    rows = []
    for name, rows_ in groups:
        counts = rows_["act_category"].value_counts()
        row = {"group": name, "rows": len(rows_)}
        for c in CLASS_ORDER:
            row[c] = f"{int(counts.get(c, 0))} ({counts.get(c, 0) / len(rows_):.1%})"
        rows.append(row)
    return pd.DataFrame(rows)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--raw", type=Path, default=DEFAULT_RAW)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    parser.add_argument("--regenerate", action="store_true", help="re-play match 0 and compare bytes (L11b)")
    parser.add_argument("--truncation-sample", type=int, default=150)
    args = parser.parse_args()

    manifest = load_manifest(DEFAULT_MANIFEST_DIR / PILOT_MANIFEST_NAME)
    main_manifest = load_manifest(DEFAULT_MANIFEST_DIR / MAIN_MANIFEST_NAME)
    frame = load_dataset(manifest, args.raw)
    summary = json.loads((args.raw / "generation_summary.json").read_text(encoding="utf-8"))
    report: dict = {"manifest": manifest["name"]}
    md: list[str] = ["# Phase 3 pilot report", "",
                     "Generated by `scripts/pilot_report.py`. Pilot data is for pipeline validation only; "
                     "it is never used for training, tuning or reported results.", ""]

    # 1. Size -------------------------------------------------------------------------------
    per_match = []
    for spec in match_specs(manifest):
        rows = frame[frame["id_match_number"] == spec.number]
        per_match.append({
            "match": spec.number, "split": spec.split, "hero": spec.hero, "villain": spec.villain,
            "hands": rows["id_hand_index"].nunique(), "rows": len(rows),
            "rows/hand": len(rows) / rows["id_hand_index"].nunique(),
            "hero rows": int((rows["label_actor_role"] == "hero").sum()),
            "villain rows": int((rows["label_actor_role"] == "villain").sum()),
            "scored rows": int(rows["id_scored"].sum()),
        })
    per_match = pd.DataFrame(per_match)
    report["size"] = {"total_rows": len(frame), "scored_rows": int(frame["id_scored"].sum()),
                      "per_match": per_match.to_dict("records")}
    md += ["## 1. Dataset size", "", f"Total decision rows: **{len(frame)}** "
           f"(scored: {int(frame['id_scored'].sum())}).", "", md_table(per_match, "{:.2f}"), ""]

    # 2. Runtime ----------------------------------------------------------------------------
    timings = pd.DataFrame(summary["matches"])
    timings["dec/s"] = timings["decisions"] / timings["seconds"]
    mean_rows = per_match["rows"].mean()
    mean_seconds = timings["seconds"].mean()
    aggregate_rate = timings["decisions"].sum() / timings["seconds"].sum()
    warmup = timings["worker_warmup_seconds"].max()
    workers = summary["workers"]
    projected_rows = mean_rows * FULL_MATCHES
    projected_single = projected_rows / aggregate_rate
    projected_wall = math.ceil(FULL_MATCHES / workers) * mean_seconds + warmup
    report["runtime"] = {
        "workers": workers, "wall_seconds": summary["wall_seconds"], "warmup_seconds": warmup,
        "per_match": timings[["number", "seconds", "decisions", "dec/s"]].to_dict("records"),
        "decisions_per_second_per_process": aggregate_rate,
        "projected_full_rows": projected_rows,
        "projected_full_single_process_minutes": projected_single / 60,
        "projected_full_wall_minutes": projected_wall / 60,
        "machine": summary["machine"],
    }
    md += ["## 2. Runtime", "",
           f"{workers} worker processes on {summary['machine']['cpu_count']} CPUs; wall time "
           f"{summary['wall_seconds']:.1f} s including a preflop-cache warm-up of up to {warmup:.1f} s per worker.", "",
           md_table(timings[["number", "seconds", "decisions", "dec/s"]], "{:.1f}"), "",
           f"Mean speed per process: **{aggregate_rate:.1f} decisions/s**.", "",
           f"Projection for the full 48-match dataset (mean {mean_rows:.0f} rows per pilot match): "
           f"about **{projected_rows:,.0f} rows**, about {projected_single / 60:.0f} min in one process, or "
           f"about **{projected_wall / 60:.0f} min wall time with {workers} workers** "
           f"({math.ceil(FULL_MATCHES / workers)} rounds of {workers} matches x {mean_seconds:.0f} s, plus warm-up). "
           "This is an extrapolation from 4 matches, not a measurement.", ""]

    # 3. Action distribution ----------------------------------------------------------------
    overall = frame["act_category"].value_counts(normalize=True)
    rare = [c for c in CLASS_ORDER if overall.get(c, 0.0) < RARE_SHARE]
    report["actions"] = {
        "overall": {c: int((frame["act_category"] == c).sum()) for c in CLASS_ORDER},
        "by_family": {f: {c: int((g["act_category"] == c).sum()) for c in CLASS_ORDER}
                      for f, g in frame.groupby("label_actor_family")},
        "rare_classes_below_1pct": rare,
    }
    md += ["## 3. Action distribution", "", "Overall:", "", md_table(action_table(frame, None)), "",
           "By the acting player's style family (evaluation-only label):", "",
           md_table(action_table(frame, "label_actor_family")), "",
           "By street:", "", md_table(action_table(frame, "obs_street")), "",
           f"Classes below {RARE_SHARE:.0%} of rows: {', '.join(rare) if rare else 'none'}.", ""]

    # 4. Features -----------------------------------------------------------------------------
    priors = fit_priors(prior_rows(frame, manifest))
    features_a = feature_set_a(frame)
    features_b = feature_set_b(frame, priors)
    b_only = features_b[list(B_FEATURES)]
    hands = prior_hand_count(features_b)
    first_deal = frame["id_deal_index"] == 0
    prior_values = {
        **{f"b_open_{k}": v for k, v in priors.open_rates.items()},
        **{f"b_face_{k}": v for k, v in priors.face_rates.items()},
        "b_vpip": priors.vpip, "b_pfr": priors.pfr,
    }
    deal0_equals_prior = all(
        (b_only.loc[first_deal, name] - value).abs().max() < 1e-12 for name, value in prior_values.items()
    ) and (hands[first_deal] == 0).all()
    ordered = pd.DataFrame({"m": frame["id_match"], "r": player_role(frame), "d": frame["id_deal_index"],
                            "h": hands}).sort_values(["m", "r", "d"])
    monotone = bool((ordered.groupby(["m", "r"])["h"].diff().dropna() >= 0).all())
    constant_a = [c for c in features_a.columns if features_a[c].nunique() == 1]
    late = frame["id_deal_index"] >= 40
    style_table = (
        b_only.loc[late, ["b_face_fold", "b_face_call", "b_open_check", "b_vpip", "b_pfr"]]
        .groupby(frame.loc[late, "label_actor_family"]).mean().reset_index()
        .rename(columns={"label_actor_family": "family"})
    )
    prior_row = pd.DataFrame([{"family": "(prior)", "b_face_fold": priors.face_rates["fold"],
                               "b_face_call": priors.face_rates["call"], "b_open_check": priors.open_rates["check"],
                               "b_vpip": priors.vpip, "b_pfr": priors.pfr}])
    checks = {
        "feature_set_a_shape": list(features_a.shape),
        "feature_set_b_shape": list(features_b.shape),
        "missing_values_a": int(features_a.isna().sum().sum()),
        "missing_values_b": int(features_b.isna().sum().sum()),
        "constant_columns_a": constant_a,
        "b_rates_within_0_1": bool(((b_only.drop(columns=["b_log_prior_hands", "b_log_prior_decisions"]) >= 0)
                                    & (b_only.drop(columns=["b_log_prior_hands", "b_log_prior_decisions"]) <= 1)).all().all()),
        "deal0_equals_priors_with_zero_counts": bool(deal0_equals_prior),
        "prior_hand_counts_never_decrease": monotone,
        "max_prior_hands": int(hands.max()),
        "priors": priors.to_dict(),
    }
    report["features"] = checks
    md += ["## 4. Feature validation", "",
           f"- Feature Set A: {features_a.shape[1]} features; Feature Set B: {features_b.shape[1]} features "
           f"({len(B_FEATURES)} history features), {features_b.shape[0]} rows.",
           f"- Missing values: A = {checks['missing_values_a']}, B = {checks['missing_values_b']}.",
           f"- Constant columns in the pilot (no information here): {', '.join(constant_a) or 'none'}.",
           f"- History rates within [0, 1]: {checks['b_rates_within_0_1']}.",
           f"- Deal 0 features equal the priors with zero counts: {checks['deal0_equals_priors_with_zero_counts']}.",
           f"- Earlier-hand counts never decrease within a player's match: {monotone} "
           f"(maximum {checks['max_prior_hands']} earlier hands).",
           f"- Priors fitted on {priors.fitted_rows} `pilot_pool` rows with alpha = {priors.alpha:g}.", "",
           "Mean history features in deals 40-59 by style family (evaluation-only grouping), against the prior:", "",
           md_table(pd.concat([style_table, prior_row], ignore_index=True)), ""]

    # 5. Leakage audits ------------------------------------------------------------------------
    builders = {"A": feature_set_a, "B": lambda f: feature_set_b(f, priors)}
    start = time.perf_counter()
    results = [
        L.audit_feature_names(list(features_b.columns)),
        L.audit_scrambling(frame, builders),
        L.audit_future_truncation(frame, builders, sample=args.truncation_sample),
        L.audit_history_uses_earlier_deals(frame, priors),
        L.audit_mirror_hand_excluded(frame, priors),
        L.audit_public_replay(frame),
        L.audit_player_role(frame),
        L.audit_split_integrity(frame, [manifest, main_manifest]),
        L.audit_seed_uniqueness([main_manifest, manifest], frame),
        L.audit_train_only_priors(frame, manifest),
        L.audit_manifest_reproducible({
            "phase3": (DEFAULT_MANIFEST_DIR / MAIN_MANIFEST_NAME).read_text(encoding="utf-8"),
            "phase3_pilot": (DEFAULT_MANIFEST_DIR / PILOT_MANIFEST_NAME).read_text(encoding="utf-8"),
        }),
    ]
    if args.regenerate:
        spec = match_specs(manifest)[0]
        with tempfile.TemporaryDirectory() as temporary:
            generate_match(spec, manifest, Path(temporary))
            regenerated = (Path(temporary) / run_dir_name(spec) / "decisions.csv").read_bytes()
        original = (args.raw / run_dir_name(spec) / "decisions.csv").read_bytes()
        results.append(L.audit_regenerated_bytes(original, regenerated, run_dir_name(spec)))
    audit_seconds = time.perf_counter() - start
    report["audits"] = [r.__dict__ for r in results]
    audit_frame = pd.DataFrame([{"audit": r.audit_id, "check": r.name, "result": "PASS" if r.passed else "FAIL",
                                 "detail": r.detail} for r in results])
    md += ["## 5. Leakage and reproducibility audits", "", md_table(audit_frame), "",
           f"Audits took {audit_seconds:.0f} s.", ""]

    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / "pilot_report.md").write_text("\n".join(md), encoding="utf-8")
    (args.out / "pilot_report.json").write_text(json.dumps(report, indent=2, default=str) + "\n", encoding="utf-8")
    print("\n".join(md))
    failed = [r.audit_id for r in results if not r.passed]
    print(f"\nAudits failed: {failed}" if failed else "\nAll audits passed.")


if __name__ == "__main__":
    main()
