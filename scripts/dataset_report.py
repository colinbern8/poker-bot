"""Stage 2 report: completeness, split separation, class balance and leakage
audits for the full Phase 3 dataset.

    python scripts/dataset_report.py --regenerate 0 47

Reads data/raw/simulations/phase3_s3000/ (ignored by git) and writes
results/phase3/dataset_report.md and dataset_report.json. With
--regenerate, the listed matches are played again into a temporary folder
and their decisions.csv and hands.csv are compared byte for byte.

This script only describes and audits the data. It does not train models,
rebalance classes or change features. Labels are used only for grouping.
"""

from __future__ import annotations

import argparse
import json
import random
import tempfile
import time
from pathlib import Path

import pandas as pd

from hybridpoker import leakage as L
from hybridpoker.action_probabilities import CLASS_ORDER
from hybridpoker.dataset_generation import generate_match
from hybridpoker.dataset_loader import load_dataset, prior_rows
from hybridpoker.dataset_manifest import (
    DEFAULT_MANIFEST_DIR,
    MAIN_MANIFEST_NAME,
    PILOT_MANIFEST_NAME,
    configs_by_name,
    load_manifest,
    manifest_hash,
    match_specs,
    run_dir_name,
)
from hybridpoker.features import feature_set_a
from hybridpoker.opponent_history import feature_set_b, fit_priors
from hybridpoker.reporting import (
    EVALUATION_SET_ORDER,
    class_shares,
    evaluation_set,
    format_counts_with_shares,
    legal_conditioned,
    md_table,
    per_match_share_range,
    share_differences,
)

DEFAULT_RAW = Path("data/raw/simulations/phase3_s3000")
DEFAULT_OUT = Path("results/phase3")
RARE_SHARE = 0.01
IMBALANCE_FLAG_PP = 5.0  # descriptive flag, fixed before looking at the data


def completeness(manifest: dict, raw: Path) -> tuple[pd.DataFrame, list[str]]:
    """Check every run directory before loading anything."""
    rows, problems = [], []
    expected = {run_dir_name(s) for s in match_specs(manifest)}
    present = {p.name for p in raw.iterdir() if p.is_dir()}
    if present - expected:
        problems.append(f"unexpected run folders: {sorted(present - expected)}")
    for spec in match_specs(manifest):
        run = raw / run_dir_name(spec)
        meta_path = run / "metadata.json"
        temporary = sorted(p.name for p in run.glob("*.tmp")) if run.exists() else []
        complete = meta_path.exists()
        meta = json.loads(meta_path.read_text(encoding="utf-8")) if complete else {}
        row = {
            "match": spec.number, "split": spec.split, "metadata.json": complete,
            "hands": meta.get("hand_count"), "seed ok": meta.get("seed") == spec.seed,
            "manifest hash ok": meta.get("extra", {}).get("manifest_hash") == manifest_hash(manifest),
            "temp files": len(temporary),
        }
        if not complete or temporary or row["hands"] != 2 * spec.deal_count or not row["seed ok"] \
                or not row["manifest hash ok"]:
            problems.append(f"match {spec.number}: {row}")
        rows.append(row)
    return pd.DataFrame(rows), problems


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--raw", type=Path, default=DEFAULT_RAW)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    parser.add_argument("--regenerate", type=int, nargs="*", default=[], help="match numbers to re-play")
    parser.add_argument("--truncation-matches", type=int, default=6)
    parser.add_argument("--truncation-sample", type=int, default=300)
    args = parser.parse_args()

    manifest = load_manifest(DEFAULT_MANIFEST_DIR / MAIN_MANIFEST_NAME)
    pilot_manifest = load_manifest(DEFAULT_MANIFEST_DIR / PILOT_MANIFEST_NAME)
    configs = configs_by_name(manifest)
    report: dict = {"manifest": manifest["name"], "manifest_hash": manifest_hash(manifest)}
    md = ["# Phase 3 dataset report (Stage 2)", "",
          "Generated by `scripts/dataset_report.py` from the committed manifest "
          f"`data/manifests/{MAIN_MANIFEST_NAME}` (master seed {manifest['master_seed']}, "
          f"{len(manifest['matches'])} matches, {manifest['deal_count']} seat-swapped deals each). "
          "Descriptive only: no models were trained and nothing was rebalanced.", ""]

    # 1. Completeness ------------------------------------------------------------------------
    status, problems = completeness(manifest, args.raw)
    frame = load_dataset(manifest, args.raw)  # also validates seeds, configurations and hash per run
    frame["eval_set"] = evaluation_set(frame)
    report["completeness"] = {"matches": len(status), "complete": int(status["metadata.json"].sum()),
                              "problems": problems}
    md += ["## 1. Completeness", "",
           f"- Run folders with the `metadata.json` completion marker: **{int(status['metadata.json'].sum())} "
           f"of {len(status)}**.",
           f"- Every run has {2 * manifest['deal_count']} hands, the manifest seed and the manifest hash: "
           f"{'yes' if not problems else 'NO'}; leftover temporary files: {int(status['temp files'].sum())}.",
           "- Every run also passed the loader's checks (both agents' full configurations equal the manifest).",
           *(f"- PROBLEM: {p}" for p in problems), ""]

    # 2. Runtime -----------------------------------------------------------------------------
    summary = json.loads((args.raw / "generation_summary.json").read_text(encoding="utf-8"))
    timing = pd.DataFrame(summary["matches"])
    total_decisions = int(timing["decisions"].sum())
    runtime = {
        "workers": summary["workers"], "cpu_count": summary["machine"]["cpu_count"],
        "wall_seconds": summary["wall_seconds"], "decisions": total_decisions,
        "decisions_per_wall_second": total_decisions / summary["wall_seconds"],
        "decisions_per_process_second": total_decisions / timing["seconds"].sum(),
        "match_seconds_min": timing["seconds"].min(), "match_seconds_max": timing["seconds"].max(),
        "match_seconds_mean": timing["seconds"].mean(),
        "warmup_seconds_max": timing["worker_warmup_seconds"].max(),
        "git_commit_at_end": summary["versions"].get("git_commit_at_end", summary["versions"].get("git_commit")),
        "git_commit_at_start": summary["versions"].get("git_commit_at_start"),
    }
    commits = {}
    for spec in match_specs(manifest):
        meta = json.loads((args.raw / run_dir_name(spec) / "metadata.json").read_text(encoding="utf-8"))
        commits[meta["versions"]["git_commit"][:7]] = commits.get(meta["versions"]["git_commit"][:7], 0) + 1
    runtime["per_match_metadata_commits"] = commits
    report["runtime"] = runtime
    md += ["## 2. Generation runtime (measured)", "",
           f"- {runtime['workers']} worker processes on {runtime['cpu_count']} CPUs.",
           f"- Git commit recorded per match (at the moment each match was written): "
           + ", ".join(f"`{c}` x {n}" for c, n in sorted(commits.items())) + "; summary commit at start: "
           f"`{(runtime['git_commit_at_start'] or 'not recorded')[:7]}`, at end: `{runtime['git_commit_at_end'][:7]}`.",
           f"- Wall time: **{runtime['wall_seconds'] / 60:.1f} min** for {total_decisions:,} decisions "
           f"(**{runtime['decisions_per_wall_second']:.1f} decisions/s overall**, "
           f"{runtime['decisions_per_process_second']:.1f} decisions/s per process).",
           f"- Match times: {runtime['match_seconds_min']:.0f}-{runtime['match_seconds_max']:.0f} s "
           f"(mean {runtime['match_seconds_mean']:.0f} s); preflop-cache warm-up up to "
           f"{runtime['warmup_seconds_max']:.0f} s per worker.", ""]

    # 3. Decision counts ---------------------------------------------------------------------
    per_match = frame.groupby(["id_match_number", "id_split"]).size().rename("rows").reset_index()
    by_split = per_match.groupby("id_split", sort=False)["rows"].agg(["count", "sum", "mean", "min", "max"])
    by_split = by_split.reindex(["train", "validation", "test", "heldout"]).reset_index()
    by_split.columns = ["split", "matches", "rows (all)", "mean/match", "min/match", "max/match"]
    by_split["rows used for evaluation/training"] = [
        int((frame["eval_set"] == s).sum()) for s in by_split["split"]
    ]
    used = frame[frame["eval_set"].notna()]
    family_split = (
        used.groupby(["label_actor_family", "eval_set"]).size().unstack(fill_value=0)
        .reindex(columns=list(EVALUATION_SET_ORDER), fill_value=0)
    )
    family_split["total"] = family_split.sum(axis=1)
    family_split = family_split.reset_index().rename(columns={"label_actor_family": "family"})
    config_rows = used.groupby(["label_actor_agent", "eval_set"]).size().unstack(fill_value=0) \
        .reindex(columns=list(EVALUATION_SET_ORDER), fill_value=0).reset_index() \
        .rename(columns={"label_actor_agent": "configuration"})
    report["counts"] = {
        "total_rows": len(frame), "used_rows": len(used),
        "unused_heldout_counterpart_rows": int(frame["eval_set"].isna().sum()),
        "by_split": by_split.to_dict("records"), "by_family_and_set": family_split.to_dict("records"),
        "by_configuration_and_set": config_rows.to_dict("records"),
    }
    md += ["## 3. Decision counts (measured)", "",
           f"Total decision rows generated: **{len(frame):,}**. Rows used for training or evaluation: "
           f"**{len(used):,}**; the other {int(frame['eval_set'].isna().sum()):,} are the training-pool "
           "counterparts' decisions in held-out matches, which are not scored or trained on.", "",
           md_table(by_split, "{:.1f}"), "",
           "Rows used, by the acting player's style family and set:", "", md_table(family_split), "",
           "Rows used, by configuration and set:", "", md_table(config_rows), ""]

    # 4. Split separation --------------------------------------------------------------------
    configs_per_set = used.groupby("eval_set")["label_actor_agent"].unique()
    heldout_names = sorted(n for n, c in configs.items() if c.pool == "heldout")
    separation = {
        "matches_in_more_than_one_split": int((frame.groupby("id_match")["id_split"].nunique() > 1).sum()),
        "heldout_configs": heldout_names,
        "heldout_configs_in_train_validation_test_rows": sorted(
            set(frame.loc[frame["id_split"] != "heldout", "label_actor_agent"]) & set(heldout_names)
        ),
        "configs_scored_in_heldout_set": sorted(configs_per_set.get("heldout", [])),
        "train_configs_in_validation_or_test_not_in_train": sorted(
            (set(configs_per_set.get("validation", [])) | set(configs_per_set.get("test", [])))
            - set(configs_per_set.get("train", []))
        ),
        "deal_seeds_shared_between_matches": int((frame.groupby("id_deal_seed")["id_match"].nunique() > 1).sum()),
        "matches_per_split": {s: int(n) for s, n in frame.groupby("id_split")["id_match"].nunique().items()},
    }
    report["separation"] = separation
    md += ["## 4. Split separation", "",
           f"- Matches per split: {separation['matches_per_split']}.",
           f"- Matches appearing in more than one split: {separation['matches_in_more_than_one_split']}.",
           f"- Held-out configurations: {', '.join(heldout_names)}. Rows from them in train/validation/test: "
           f"{separation['heldout_configs_in_train_validation_test_rows'] or 'none'}.",
           f"- Configurations scored in the held-out set: {', '.join(separation['configs_scored_in_heldout_set'])}.",
           f"- Validation/test configurations missing from train: "
           f"{separation['train_configs_in_validation_or_test_not_in_train'] or 'none'}.",
           f"- Deal seeds shared between matches: {separation['deal_seeds_shared_between_matches']}.",
           "- Audits L8 (split integrity) and L9 (seed uniqueness) below check the same properties "
           "against both manifests.", ""]

    # 5. Action distributions ----------------------------------------------------------------
    md += ["## 5. Action-class distribution (rows used)", "", "Overall:", "",
           md_table(format_counts_with_shares(used)), "",
           "By style family:", "", md_table(format_counts_with_shares(used, "label_actor_family")), "",
           "By set:", "", md_table(format_counts_with_shares(
               used.assign(eval_set=pd.Categorical(used["eval_set"], EVALUATION_SET_ORDER)).sort_values("eval_set"),
               "eval_set")), ""]
    report["actions"] = {
        "overall": format_counts_with_shares(used).to_dict("records"),
        "by_family": format_counts_with_shares(used, "label_actor_family").to_dict("records"),
        "by_set": format_counts_with_shares(used, "eval_set").to_dict("records"),
    }

    # 6. Legal-action conditioning -------------------------------------------------------------
    legal_report = {}
    md += ["## 6. Actions conditioned on legal availability (rows used)", "",
           "`legal share` = fraction of decisions where the action was legal; "
           "`chosen | legal` = how often it was chosen when legal.", ""]
    for category in ("fold", "all_in"):
        overall = legal_conditioned(used, category)
        family = legal_conditioned(used, category, "label_actor_family")
        by_set = legal_conditioned(used, category, "eval_set")
        legal_report[category] = {"overall": overall.to_dict("records"), "by_family": family.to_dict("records"),
                                  "by_set": by_set.to_dict("records")}
        md += [f"**{category}:**", "", md_table(pd.concat([overall, family, by_set], ignore_index=True)), ""]
    availability = pd.DataFrame([{"action": c, "legal share": used[f"obs_legal_{c}"].astype(bool).mean(),
                                  "chosen share": (used["act_category"] == c).mean(),
                                  "chosen | legal": (used["act_category"] == c).sum()
                                  / used[f"obs_legal_{c}"].astype(bool).sum()} for c in CLASS_ORDER])
    legal_report["all_actions"] = availability.to_dict("records")
    report["legal_conditioned"] = legal_report
    md += ["All five actions:", "", md_table(availability), ""]

    # 7. Rare classes and imbalance across sets -------------------------------------------------
    shares = class_shares(used, "eval_set").set_index("group").reindex(EVALUATION_SET_ORDER).reset_index()
    diffs = share_differences(shares)
    overall_shares = class_shares(used).iloc[0]
    rare = [c for c in CLASS_ORDER if overall_shares[c] < RARE_SHARE]
    rare_by_set = {s: [c for c in CLASS_ORDER if shares.set_index("group").loc[s, c] < RARE_SHARE]
                   for s in EVALUATION_SET_ORDER}
    flagged_sets = diffs.loc[diffs["max |diff| (pp)"] > IMBALANCE_FLAG_PP, "group"].tolist()
    ranges = per_match_share_range(used, "eval_set")
    report["imbalance"] = {"rare_overall": rare, "rare_by_set": rare_by_set,
                           "share_differences_pp": diffs.to_dict("records"),
                           "sets_over_flag": flagged_sets, "per_match_ranges": ranges.to_dict("records")}
    md += ["## 7. Rare classes and class balance across sets", "",
           f"- Classes below {RARE_SHARE:.0%} of rows used: **{', '.join(rare) or 'none'}**.",
           f"- Below {RARE_SHARE:.0%} within a set: " + "; ".join(f"{s}: {', '.join(v) or 'none'}"
                                                              for s, v in rare_by_set.items()) + ".",
           "", "Class shares by set minus train shares, in percentage points:", "", md_table(diffs, "{:+.2f}"), "",
           f"Sets differing from train by more than {IMBALANCE_FLAG_PP:g} percentage points in any class: "
           f"**{', '.join(flagged_sets) or 'none'}**.", "",
           "Range of each class's share across the individual matches in each set:", "", md_table(ranges), ""]

    # 8. Leakage audits ------------------------------------------------------------------------
    priors = fit_priors(prior_rows(frame, manifest))
    builders = {"A": feature_set_a, "B": lambda f: feature_set_b(f, priors)}
    rng = random.Random(manifest["master_seed"])
    subset_numbers = []
    for split, count in (("train", 2), ("validation", 1), ("test", 1), ("heldout", 2)):
        candidates = [s.number for s in match_specs(manifest) if s.split == split]
        subset_numbers += sorted(rng.sample(candidates, count))
    subset = frame[frame["id_match_number"].isin(subset_numbers[: args.truncation_matches])]
    features_b = feature_set_b(frame, priors)
    timings, results = {}, []

    def run(name, fn):
        start = time.perf_counter()
        result = fn()
        timings[name] = time.perf_counter() - start
        results.append(result)
        print(f"  {result.audit_id}: {'PASS' if result.passed else 'FAIL'} ({timings[name]:.0f} s)", flush=True)

    print("Running audits...", flush=True)
    run("L1", lambda: L.audit_feature_names(list(features_b.columns)))
    run("L2", lambda: L.audit_scrambling(frame, builders))
    run("L3", lambda: L.audit_future_truncation(subset, builders, sample=args.truncation_sample))
    run("L4", lambda: L.audit_history_uses_earlier_deals(frame, priors))
    run("L5", lambda: L.audit_mirror_hand_excluded(frame, priors))
    run("L6", lambda: L.audit_public_replay(frame))
    run("L7", lambda: L.audit_player_role(frame))
    run("L8", lambda: L.audit_split_integrity(frame, [manifest, pilot_manifest]))
    run("L9", lambda: L.audit_seed_uniqueness([manifest, pilot_manifest], frame))
    run("L10", lambda: L.audit_train_only_priors(frame, manifest))
    run("L11a", lambda: L.audit_manifest_reproducible({
        "phase3": (DEFAULT_MANIFEST_DIR / MAIN_MANIFEST_NAME).read_text(encoding="utf-8"),
        "phase3_pilot": (DEFAULT_MANIFEST_DIR / PILOT_MANIFEST_NAME).read_text(encoding="utf-8"),
    }))
    specs = {s.number: s for s in match_specs(manifest)}
    for number in args.regenerate:
        spec = specs[number]
        with tempfile.TemporaryDirectory() as temporary:
            start = time.perf_counter()
            generate_match(spec, manifest, Path(temporary))
            for name in ("decisions.csv", "hands.csv"):
                regenerated = (Path(temporary) / run_dir_name(spec) / name).read_bytes()
                original = (args.raw / run_dir_name(spec) / name).read_bytes()
                results.append(L.audit_regenerated_bytes(original, regenerated,
                                                         f"{run_dir_name(spec)} ({spec.split}) {name}"))
            timings[f"L11b match {number}"] = time.perf_counter() - start
            print(f"  L11b match {number}: {'PASS' if all(r.passed for r in results[-2:]) else 'FAIL'}", flush=True)

    report["audits"] = [r.__dict__ for r in results]
    report["audit_seconds"] = timings
    report["l3_subset_matches"] = subset_numbers[: args.truncation_matches]
    audit_table = pd.DataFrame([{"audit": r.audit_id, "check": r.name, "result": "PASS" if r.passed else "FAIL",
                                 "detail": r.detail} for r in results])
    md += ["## 8. Leakage and reproducibility audits (full dataset)", "",
           f"History priors fitted on the {priors.fitted_rows:,} train-split rows only (alpha = {priors.alpha:g}).",
           "", md_table(audit_table), "",
           f"L3 rebuilds all features once per sampled row, so it runs on {args.truncation_sample} rows sampled "
           f"from matches {subset_numbers[: args.truncation_matches]} (2 train, 1 validation, 1 test, 2 held-out; "
           "chosen with the master seed). L4 and L5 check sampled deals in every match. "
           "All other audits cover every row. "
           f"Audit time: {sum(timings.values()) / 60:.1f} min.", ""]

    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / "dataset_report.md").write_text("\n".join(md), encoding="utf-8")
    (args.out / "dataset_report.json").write_text(json.dumps(report, indent=2, default=str) + "\n",
                                                  encoding="utf-8")
    print("\n".join(md))
    failed = [r.audit_id for r in results if not r.passed]
    print(f"\nAudits failed: {failed}" if failed or problems else "\nAll checks and audits passed.")


if __name__ == "__main__":
    main()
