"""Independent verification of the Phase 4D final evaluation (read-only; changes nothing).

    python scripts/phase4_verify_final.py --report results/phase4/stage4d_final_summary.json

Run from a checkout of the frozen tag ``phase4-freeze`` with the final match
checkpoints in data/processed/phase4_final/ (see docs/phase4_codespaces_guide.md).
It uses only the frozen package code and checks:

1. all 64 matches and 8 replays are present, error-free and complete
   (the frozen ``collect`` and ``primary_analysis``, which refuse invalid runs);
2. the pre-specified endpoints recomputed from the raw records equal the
   endpoints in the run's summary JSON exactly;
3. the first deals of selected matches replayed on *this* machine reproduce the
   stored records exactly (cards, hero actions, chips): a cross-machine check;
4. post hoc and clearly labelled: leave-one-opponent-out and leave-one-style-out
   estimates of the primary comparison. These are descriptive only and never
   replace the registered result.

Writes results/phase4/stage4d_verification.md.
"""

from __future__ import annotations

import argparse
import json
import math
import platform
import sys
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path

from hybridpoker.dataset_generation import warm_preflop_cache
from hybridpoker.opponent_predictor import PHASE4_MODEL_PATH, file_sha256
from hybridpoker.phase4_eval import play_match_records
from hybridpoker.phase4_final import (
    FINAL_DIR,
    MANIFEST_PATH,
    collect,
    jobs_from_manifest,
    load_manifest,
    paired_estimates,
    primary_analysis,
)

REPLAY_OPPONENTS = ("maniac_v3", "solid_v1")
REPLAY_DEALS = 6
OUT = Path("results/phase4/stage4d_verification.md")


def _replay(job):
    hero, config, seed, _, index = job
    return hero, config.name, play_match_records(hero, config, seed, REPLAY_DEALS, index)


def _hands(record):
    return [(h["deal_index"], h["seat_swap"], h["hero_net"], h["cards_hash"]) for h in record["hands"]
            if h["deal_index"] < REPLAY_DEALS]


def _actions(record):
    return [(d["deal_index"], d["seat_swap"], d["category"]) for d in record["decisions"]
            if d["deal_index"] < REPLAY_DEALS]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--report", type=Path, required=True, help="the run's stage4d_final_summary.json")
    parser.add_argument("--workers", type=int, default=4)
    args = parser.parse_args()

    manifest = load_manifest(MANIFEST_PATH)
    main_jobs, replay_jobs = jobs_from_manifest(manifest)
    records = collect(main_jobs, replay_jobs, FINAL_DIR)
    endpoints = primary_analysis(records["results"], manifest)  # raises on any failed or incomplete match
    reported = json.loads(args.report.read_text(encoding="utf-8"))["endpoints"]
    endpoints_equal = json.loads(json.dumps(endpoints)) == reported
    model_ok = file_sha256(PHASE4_MODEL_PATH) == manifest["model"]["sha256"]
    run_ids = sorted({r["run_id"] for r in records["results"] + records["replays"]})

    by = {(r["hero"], r["opponent"]): r for r in records["results"]}
    targets = [j for j in main_jobs if j[1].name in REPLAY_OPPONENTS]
    rows, replay_ok = [], True
    with ProcessPoolExecutor(args.workers, initializer=warm_preflop_cache, initargs=([500, 200],)) as pool:
        for hero, opponent, again in pool.map(_replay, targets):
            stored = by[(hero, opponent)]
            same = again["error"] is None and _hands(again) == _hands(stored) and _actions(again) == _actions(stored)
            replay_ok &= same
            rows.append(f"| {hero} | {opponent} | {stored['run_id']} | {len(_hands(stored))} | "
                        f"{len(_actions(stored))} | {'identical' if same else 'DIFFERENT'} |")

    names = [o["name"] for o in manifest["opponents"]]
    family = {o["name"]: o["family"] for o in manifest["opponents"]}
    per = paired_estimates(records["results"], "ev_ml", "ev_situation", manifest["deals_per_match"], names)

    def equal_weight(subset):
        mean = sum(per[n].mean for n in subset) / len(subset)
        se = math.sqrt(sum(per[n].se ** 2 for n in subset)) / len(subset)
        return mean, mean - 1.96 * se, mean + 1.96 * se

    loo = [(n, *equal_weight([x for x in names if x != n])) for n in names]
    styles = [(f, *equal_weight([x for x in names if family[x] != f]))
              for f in ("calling_station", "maniac", "nit", "solid")]
    primary = endpoints["ML EV minus Situation-Aware Frequency EV"]["estimate"]

    lines = [
        "# Stage 4D final evaluation: independent verification",
        "",
        "Generated by `scripts/phase4_verify_final.py` (read-only). It re-checks the final run with the frozen "
        "package code; nothing here changes or replaces the registered result.",
        "",
        f"- Checked on: Python {platform.python_version()}, {platform.platform()}.",
        f"- Matches: {len(records['results'])} of 64 and replays: {len(records['replays'])} of 8, all complete and "
        "error-free (the frozen `primary_analysis` refuses anything else).",
        f"- Run sessions (`run_id`): {', '.join(run_ids)}.",
        f"- Model SHA-256 equals the manifest: {'yes' if model_ok else 'NO'}.",
        f"- Pre-specified endpoints recomputed from the raw records equal the run's summary exactly: "
        f"{'yes' if endpoints_equal else 'NO'}. Primary: {primary['mean']:+.1f} bb/100, 95% CI "
        f"[{primary['low']:+.1f}, {primary['high']:+.1f}].",
        f"- Cross-machine replay (first {REPLAY_DEALS} deals re-played on this machine): "
        f"{'all identical' if replay_ok else 'MISMATCH'}.",
        "",
        "## Cross-machine replay",
        "",
        "| hero | opponent | stored run | hands | hero decisions | result |",
        "|---|---|---|---|---|---|",
        *rows,
        "",
        "## Post hoc robustness of the primary comparison (descriptive only)",
        "",
        "Not part of the registered analysis. Equal-weight ML EV minus Situation-Aware Frequency EV after "
        "removing one opponent, or one whole style, at a time.",
        "",
        f"- Leave one opponent out: estimates from {min(t[1] for t in loo):+.1f} to {max(t[1] for t in loo):+.1f} "
        f"bb/100; the lowest lower 95% bound is {min(t[2] for t in loo):+.1f} "
        f"(dropping {min(loo, key=lambda t: t[2])[0]}).",
        f"- Opponents with a positive point estimate: {sum(per[n].mean > 0 for n in names)} of 16.",
        "",
        "| style removed | estimate | 95% interval |",
        "|---|---|---|",
        *[f"| {f} | {m:+.1f} | [{a:+.1f}, {b:+.1f}] |" for f, m, a, b in styles],
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print("\n".join(lines))
    return 0 if (endpoints_equal and replay_ok and model_ok) else 1


if __name__ == "__main__":
    sys.exit(main())
